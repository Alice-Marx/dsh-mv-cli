#!/usr/bin/env node
// Turns template/** (examples, prompt templates) into .dsh-plugin/shared/mv-template-assets.gen.mjs,
// a plain module of strings shipped with the plugin. `/*@grid*/` markers are replaced by
// template/examples/_grid.js so every example stays a standalone scene file.
// Usage: node scripts/gen-template.mjs [--check]
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'template')
const out = join(root, '.dsh-plugin/shared/mv-template-assets.gen.mjs')

export function collectTemplateAssets(dir = src) {
  const grid = readFileSync(join(dir, 'examples/_grid.js'), 'utf8').trimEnd()
  const files = {}
  const walk = d => {
    for (const name of readdirSync(d).sort()) {
      const full = join(d, name)
      if (statSync(full).isDirectory()) { walk(full); continue }
      if (name.startsWith('_') || name.startsWith('.')) continue
      const rel = relative(dir, full).split(sep).join('/')
      let text = readFileSync(full, 'utf8').replace(/\r\n/g, '\n')
      text = text.replace('/*@grid*/', grid)
      files[rel] = text
    }
  }
  walk(dir)
  return files
}

export function renderAssetsModule(files) {
  const body = Object.entries(files).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')
  return `// Generated by scripts/gen-template.mjs from template/** — do not edit by hand.\n// Example scenes and prompt templates for MV packs (see template/examples/README.md).\nexport const TEMPLATE_ASSETS = Object.freeze({\n${body}\n})\n`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderAssetsModule(collectTemplateAssets())
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(out, 'utf8') } catch {}
    if (current !== text) { console.error('mv-template-assets.gen.mjs is out of date: run node scripts/gen-template.mjs'); process.exit(1) }
    console.log('template assets up to date')
  } else {
    writeFileSync(out, text)
    console.log(`wrote ${relative(root, out)} (${Object.keys(collectTemplateAssets()).length} files, ${Buffer.byteLength(text)} bytes)`)
  }
}
