/** Sections for x-dsh-mv-ai from [start, label, …] chapter rows. */
const sections = (rows, duration, label = r => r[1]) => rows.map((r, i) => ({ kind: 'chapter', label: label(r), start: r[0], end: rows[i + 1]?.[0] ?? duration }))

/** Splits lines longer than MAX_LINE at "],[" / ", " boundaries (generated tables) so the workshop's minified-code check passes. */
function splitLongLines(code) {
  return code.split('\n').flatMap(line => {
    if (line.length <= MAX_LINE) return [line]
    const indent = line.match(/^\s*/)[0] + '  '
    const pieces = []
    let rest = line
    while (rest.length > MAX_LINE) {
      let cut = rest.lastIndexOf('],', MAX_LINE)
      if (cut < 0) cut = rest.lastIndexOf(', ', MAX_LINE)
      if (cut < 0) throw new Error(`cannot split a ${line.length}-character line: ${line.slice(0, 80)}…`)
      pieces.push(rest.slice(0, cut + 2)); rest = indent + rest.slice(cut + 2).trimStart()
    }
    return [...pieces, rest]
  })
}

export async function sceneScript() {
  const result = await build({
    entryPoints: [path.join(here, 'world-execute-me/scene-entry.mjs')], bundle: true, write: false, format: 'esm', platform: 'neutral',
    charset: 'utf8', legalComments: 'none', target: 'es2020', treeShaking: true,
  })
  let code = result.outputFiles[0].text
  code = code.replace(/^export\s*\{\s*render\s*\};?\s*$/m, '')
  if (/^\s*export\b/m.test(code)) throw new Error('unexpected export left in scenes.js')
  const header = [
    '// scenes.js — world.execute(me); ASCII scenes for dsh-mv (canvas.renderer "script").',
    '// Scenes: port of yym8224961/world.execute-me-ascii (野生大K), https://github.com/yym8224961/world.execute-me-ascii,',
    '// used and redistributed with the author\'s permission (2026-10-03). Not open source: no reuse outside this pack',
    '// without the author\'s permission. Song and lyrics © Mili (not included). Generated by dsh-mv-cli',
    '// presets/build-workshop-packs.mjs from presets/world-execute-me/ — readable source: https://github.com/Alice-Marx/dsh-mv-cli/tree/main/presets/world-execute-me',
    '',
  ].join('\n')
  // Closure-scoped so only render is a global (top-level names on a vm / worker global are much slower to look up).
  const body = splitLongLines(code).join('\n').trimEnd()
  // Built-ins are passed in as parameters for the same reason.
  const globals = ['Math', 'Array', 'String', 'Number', 'Object', 'Map', 'Set', 'Error', 'TypeError', 'Symbol', 'BigInt', 'JSON'].filter(g => new RegExp(`\\b${g}\\b`).test(body)).join(', ')
  return `${header}var render = ((${globals}) => {\n${body}\nreturn render\n})(${globals})\n`
}

/** Splits a JSON object into shards ≤ SHARD_BYTES: the first holds every non-array key; arrays are spread in order. */
export function shardJson(value) {
  const first = {}, arrays = []
  for (const [k, v] of Object.entries(value)) (Array.isArray(v) ? arrays.push([k, v]) : (first[k] = v))
  const shards = [first]
  let cur = first, size = Buffer.byteLength(jsonCompact(first))
  for (const [k, list] of arrays) {
    for (const item of list) {
      const n = Buffer.byteLength(JSON.stringify(item)) + 1
      if (size + n > SHARD_BYTES && (cur !== first || Object.keys(cur).some(key => Array.isArray(cur[key])))) { cur = {}; shards.push(cur); size = 2 }
      ;(cur[k] ??= []).push(item); size += n + (cur[k].length === 1 ? k.length + 4 : 0)
    }
    if (!(k in first) && shards.length === 1) first[k] = []
  }
  for (const s of shards) if (Buffer.byteLength(jsonCompact(s)) > 512 * 1024) throw new Error('shard too large')
  return shards
}

async function copyCover(id, dir) {
  const file = path.join(coverDir, `${id}.png`)
  if (existsSync(file)) { await copyFile(file, path.join(dir, 'cover.png')); return true }
  console.warn(`! no cover for ${id} (${file})`)
  return false
}

